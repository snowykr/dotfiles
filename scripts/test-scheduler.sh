#!/bin/sh
set -eu
repo=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd -P)
root=$(mktemp -d)
root=$(CDPATH= cd -- "$root" && pwd -P)
trap 'rm -rf "$root"' EXIT
trap 'exit 129' HUP
trap 'exit 130' INT
trap 'exit 143' TERM
mkdir -p "$root/stubs" "$root/missing"
cat > "$root/stubs/uname" <<'EOF'
#!/bin/sh
printf '%s\n' "$MOCK_OS"
EOF
cat > "$root/stubs/id" <<'EOF'
#!/bin/sh
[ "$1" = -u ] || exit 2
printf '501\n'
EOF
cat > "$root/stubs/launchctl" <<'EOF'
#!/bin/sh
[ "${MOCK_UNAVAILABLE:-0}" = 0 ] || exit 1
case "$1" in
    print)
        [ "$2" != gui/501 ] || exit 0
        [ "$2" = gui/501/com.snowykr.dotfiles.update ] || exit 2
        [ -f "$MOCK_LOADED" ]; exit $?;;
    enable|bootstrap|bootout) printf '%s\n' "$*" >> "$MOCK_LOG";;
    *) exit 2;;
esac
[ "${MOCK_FAIL:-0}" = 0 ] || exit 1
case "$1" in
    bootstrap) cp "$3" "$MOCK_LOADED";;
    bootout)
        if [ "${MOCK_BOOTOUT_FAIL_ONCE:-0}" = 1 ] && [ ! -e "$MOCK_BOOTOUT_FAILED" ]; then
            : > "$MOCK_BOOTOUT_FAILED"
            exit 1
        fi
        rm -f "$MOCK_LOADED"
        ;;
esac
EOF
cat > "$root/stubs/systemctl" <<'EOF'
#!/bin/sh
[ "$1" = --user ] || exit 2
shift
[ "${MOCK_UNAVAILABLE:-0}" = 0 ] || exit 1
manager_unit() {
    alias=$MOCK_MANAGER_CONFIG/systemd/user/$1
    [ -L "$alias" ] || return 1
    actual=$(readlink -f -- "$alias") || return 1
    [ "$actual" = "$MOCK_EXPECTED_SOURCE/$1" ] || return 1
    [ -f "$actual" ] || return 1
    grep -F -x '# Generated by dotfiles scripts/scheduler.sh' "$actual" >/dev/null
}
require_units() {
    manager_unit dotfiles-update.service && manager_unit dotfiles-update.timer
}
refresh_fragment() {
    unit=$1
    alias=$MOCK_MANAGER_CONFIG/systemd/user/$unit
    cache=$MOCK_MANAGER_CONFIG/.fragment-$unit
    mkdir -p "$MOCK_MANAGER_CONFIG"
    if [ -L "$alias" ] || [ -e "$alias" ]; then
        readlink -f -- "$alias" > "$cache" || return 1
    elif [ "$unit" = dotfiles-update.service ] && [ -f "$MOCK_SERVICE_ACTIVE" ]; then
        # Reloading does not unload an in-flight service's existing definition.
        if [ ! -f "$cache" ]; then printf '%s\n' "$MOCK_EXPECTED_SOURCE/$unit" > "$cache"; fi
    else
        printf '\n' > "$cache"
    fi
}
case "$1" in
    show-environment) [ "$#" -eq 1 ] || exit 2; exit 0;;
    show)
        [ "$#" -eq 4 ] && [ "$2" = --property=FragmentPath ] && [ "$3" = --value ] || exit 2
        case "$4" in dotfiles-update.service|dotfiles-update.timer) ;; *) exit 2;; esac
        cache=$MOCK_MANAGER_CONFIG/.fragment-$4
        if [ ! -f "$cache" ]; then refresh_fragment "$4" || exit 1; fi
        cat "$cache"
        ;;
    is-enabled)
        [ "$#" -eq 3 ] && [ "$2" = --quiet ] && [ "$3" = dotfiles-update.timer ] || exit 2
        [ -f "$MOCK_ENABLED" ]
        ;;
    is-active)
        [ "$#" -eq 3 ] && [ "$2" = --quiet ] && [ "$3" = dotfiles-update.timer ] || exit 2
        [ -f "$MOCK_LOADED" ]
        ;;
    daemon-reload)
        [ "$#" -eq 1 ] || exit 2
        printf 'daemon-reload\n' >> "$MOCK_LOG"
        refresh_fragment dotfiles-update.service && refresh_fragment dotfiles-update.timer || exit 1
        printf 'mock systemctl reply\n'
        ;;
    start|restart)
        [ "$#" -eq 2 ] && [ "$2" = dotfiles-update.timer ] || exit 2
        require_units && [ -f "$MOCK_ENABLED" ] || exit 1
        printf '%s %s\n' "$1" "$2" >> "$MOCK_LOG"
        : > "$MOCK_LOADED"
        printf 'mock systemctl reply\n'
        ;;
    stop)
        [ "$#" -eq 2 ] && [ "$2" = dotfiles-update.timer ] || exit 2
        manager_unit dotfiles-update.timer || exit 1
        printf 'stop %s\n' "$2" >> "$MOCK_LOG"
        rm -f "$MOCK_LOADED"
        printf 'mock systemctl reply\n'
        ;;
    *) exit 2;;
esac
EOF
cat > "$root/stubs/busctl" <<'EOF'
#!/bin/sh
[ "$#" -ge 7 ] && [ "$1" = --user ] || exit 2
shift
[ "$1" = call ] || exit 2
shift
[ "$1" = org.freedesktop.systemd1 ] || exit 2
shift
[ "$1" = /org/freedesktop/systemd1 ] || exit 2
shift
[ "$1" = org.freedesktop.systemd1.Manager ] || exit 2
shift
method=$1
shift
link_unit() {
    source=$1
    name=${source##*/}
    alias_dir=$MOCK_MANAGER_CONFIG/systemd/user
    alias=$alias_dir/$name
    [ -f "$source" ] && [ ! -L "$source" ] || return 1
    grep -F -x '# Generated by dotfiles scripts/scheduler.sh' "$source" >/dev/null || return 1
    mkdir -p "$alias_dir" || return 1
    if [ -L "$alias" ]; then
        old_target=$(readlink -f -- "$alias") || return 1
        new_target=$(readlink -f -- "$source") || return 1
        [ "$old_target" = "$new_target" ]
    elif [ -e "$alias" ]; then
        return 1
    else
        ln -s "$source" "$alias"
    fi
}
case "$method" in
    LinkUnitFiles)
        [ "$#" -eq 6 ] && [ "$1" = asbb ] && [ "$2" = 2 ] || exit 2
        service=$3
        timer=$4
        [ "$5" = false ] && [ "$6" = false ] || exit 2
        [ "$service" = "$MOCK_EXPECTED_SOURCE/dotfiles-update.service" ] || exit 2
        [ "$timer" = "$MOCK_EXPECTED_SOURCE/dotfiles-update.timer" ] || exit 2
        printf 'LinkUnitFiles 2\n' >> "$MOCK_LOG"
        if [ "${MOCK_LINK_FAIL_SECOND_ONCE:-0}" = 1 ] && [ ! -e "$MOCK_LINK_FAILED" ]; then
            link_unit "$service" || exit 1
            : > "$MOCK_LINK_FAILED"
            exit 1
        fi
        link_unit "$service" && link_unit "$timer" || exit 1
        printf 'mock manager reply\n'
        ;;
    EnableUnitFiles)
        [ "$#" -eq 5 ] && [ "$1" = asbb ] && [ "$2" = 1 ] && [ "$3" = dotfiles-update.timer ] && [ "$4" = false ] && [ "$5" = false ] || exit 2
        printf 'EnableUnitFiles 1 dotfiles-update.timer\n' >> "$MOCK_LOG"
        [ "${MOCK_FAIL:-0}" = 0 ] || exit 1
        service_target=$(readlink -f -- "$MOCK_MANAGER_CONFIG/systemd/user/dotfiles-update.service") || exit 1
        timer_target=$(readlink -f -- "$MOCK_MANAGER_CONFIG/systemd/user/dotfiles-update.timer") || exit 1
        [ "$service_target" = "$MOCK_EXPECTED_SOURCE/dotfiles-update.service" ] || exit 1
        [ "$timer_target" = "$MOCK_EXPECTED_SOURCE/dotfiles-update.timer" ] || exit 1
        grep -F -x '# Generated by dotfiles scripts/scheduler.sh' "$service_target" >/dev/null || exit 1
        grep -F -x '# Generated by dotfiles scripts/scheduler.sh' "$timer_target" >/dev/null || exit 1
        : > "$MOCK_ENABLED"
        printf 'mock manager reply\n'
        ;;
    DisableUnitFiles)
        [ "$#" -ge 4 ] && [ "$1" = asb ] || exit 2
        count=$2
        shift 2
        case "$count" in
            1)
                [ "$#" -eq 2 ] || exit 2
                first=$1
                [ "$2" = false ] || exit 2
                case "$first" in dotfiles-update.service|dotfiles-update.timer) ;; *) exit 2;; esac
                printf 'DisableUnitFiles 1 %s false\n' "$first" >> "$MOCK_LOG"
                rm -f "$MOCK_MANAGER_CONFIG/systemd/user/$first"
                ;;
            2)
                [ "$#" -eq 3 ] && [ "$1" = dotfiles-update.service ] && [ "$2" = dotfiles-update.timer ] && [ "$3" = false ] || exit 2
                printf 'DisableUnitFiles 2 dotfiles-update.service dotfiles-update.timer false\n' >> "$MOCK_LOG"
                rm -f "$MOCK_MANAGER_CONFIG/systemd/user/dotfiles-update.service" "$MOCK_MANAGER_CONFIG/systemd/user/dotfiles-update.timer"
                ;;
            *) exit 2;;
        esac
        rm -f "$MOCK_ENABLED"
        printf 'mock manager reply\n'
        ;;
    *) exit 2;;
esac
EOF
chmod +x "$root/stubs/"*
cp "$root/stubs/uname" "$root/missing/uname"
cp "$root/stubs/id" "$root/missing/id"
PATH="$root/stubs:$PATH"
export PATH
run() { /bin/sh "$repo/scripts/scheduler.sh" "$1" "$checkout" "$state" ${2:+"$2"}; }
expect_failure() {
    if run "$@" > "$root/error"; then printf 'Expected scheduler failure\n' >&2; exit 1; fi
    ! grep -x enabled "$root/error"
}
assert_reloaded_only() {
    cp "$1" "$root/expected-reload-log"
    printf 'daemon-reload\n' >> "$root/expected-reload-log"
    cmp "$MOCK_LOG" "$root/expected-reload-log"
}
# Literal punctuation includes XML characters, quotes, percent, dollar and backslash.
checkout="$root/repo space & < > \" ' % \$ \\"
initial_checkout=$checkout
for MOCK_OS in Darwin Linux; do
    checkout=$initial_checkout
    HOME="$root/$MOCK_OS home"
    XDG_CONFIG_HOME="$root/$MOCK_OS config & \" % \$ \\"
    XDG_STATE_HOME="$root/$MOCK_OS state & \" % \$ \\"
    state=$XDG_STATE_HOME/dotfiles
    # Explicit backend state wins over a stale caller/user-manager environment.
    XDG_STATE_HOME="$root/ignored state home"
    MOCK_LOG="$root/$MOCK_OS.mutations"
    MOCK_LOADED="$root/$MOCK_OS.loaded"
    MOCK_ENABLED="$root/$MOCK_OS.enabled"
    MOCK_SERVICE_ACTIVE="$root/$MOCK_OS.service-active"
    MOCK_BOOTOUT_FAILED="$root/$MOCK_OS.bootout-failed"
    MOCK_MANAGER_CONFIG="$root/$MOCK_OS manager default & \""
    MOCK_EXPECTED_SOURCE=$state/systemd
    MOCK_LINK_FAILED="$root/$MOCK_OS.link-failed"
    export MOCK_OS HOME XDG_CONFIG_HOME XDG_STATE_HOME MOCK_LOG MOCK_LOADED MOCK_ENABLED MOCK_SERVICE_ACTIVE MOCK_BOOTOUT_FAILED MOCK_MANAGER_CONFIG MOCK_EXPECTED_SOURCE MOCK_LINK_FAILED
    rm -f "$MOCK_LOG" "$MOCK_LOADED" "$MOCK_ENABLED" "$MOCK_SERVICE_ACTIVE" "$MOCK_LINK_FAILED"
    [ "$(run status)" = disabled ]
    [ ! -e "$HOME" ] && [ ! -e "$XDG_CONFIG_HOME" ] && [ ! -e "$state" ]
    run enable --dry-run > "$root/preview"
    run disable --dry-run > "$root/preview"
    [ ! -e "$MOCK_LOG" ] && [ ! -e "$HOME" ] && [ ! -e "$state" ] && [ ! -e "$MOCK_MANAGER_CONFIG" ]
    if [ "$MOCK_OS" = Linux ]; then
        # Foreign manager fragments are rejected without touching the manager or local state.
        mkdir -p "$MOCK_MANAGER_CONFIG/systemd/user"
        printf 'foreign unit\n' > "$root/foreign-unit"
        for foreign_unit in dotfiles-update.service dotfiles-update.timer; do
            ln -s "$root/foreign-unit" "$MOCK_MANAGER_CONFIG/systemd/user/$foreign_unit"
            systemctl --user daemon-reload >/dev/null
            cp "$MOCK_LOG" "$root/log-before-foreign" 2>/dev/null || : > "$root/log-before-foreign"
            expect_failure enable
            expect_failure disable
            [ "$(readlink "$MOCK_MANAGER_CONFIG/systemd/user/$foreign_unit")" = "$root/foreign-unit" ]
            [ ! -e "$state" ]
            if [ -e "$MOCK_LOG" ]; then cmp "$MOCK_LOG" "$root/log-before-foreign"; fi
            rm "$MOCK_MANAGER_CONFIG/systemd/user/$foreign_unit"
            systemctl --user daemon-reload >/dev/null
        done
        MOCK_LINK_FAIL_SECOND_ONCE=1; export MOCK_LINK_FAIL_SECOND_ONCE
        expect_failure enable
        [ -f "$state/systemd/dotfiles-update.service" ] && [ -f "$state/systemd/dotfiles-update.timer" ]
        [ -L "$MOCK_MANAGER_CONFIG/systemd/user/dotfiles-update.service" ]
        [ ! -e "$MOCK_MANAGER_CONFIG/systemd/user/dotfiles-update.timer" ]
        unset MOCK_LINK_FAIL_SECOND_ONCE
    fi
    [ "$(run enable)" = enabled ]
    [ "$(run status)" = enabled ]
    case "$MOCK_OS" in
        Darwin)
            definition=$HOME/Library/LaunchAgents/com.snowykr.dotfiles.update.plist
            grep -F '<string>/bin/sh</string>' "$definition"
            grep -F '<string>update</string>' "$definition"
            for minute in 0 15 30 45; do
                grep -F "<key>Minute</key><integer>$minute</integer>" "$definition"
            done
            ! grep -E 'KeepAlive|RunAtLoad|Wake' "$definition"
            grep -F '&amp; &lt; &gt; &quot; &apos; % $ \' "$definition"
            grep -F '<key>StandardOutPath</key>' "$definition"
            grep -F '<key>StandardErrorPath</key>' "$definition"
            grep -F 'scheduler.log</string>' "$definition"
            grep -F '<key>XDG_STATE_HOME</key>' "$definition"
            grep -F 'state &amp; &quot; % $ \' "$definition"
            if command -v plutil >/dev/null; then plutil -lint -- "$definition"; fi
            ;;
        Linux)
            definition=$state/systemd/dotfiles-update.service
            timer=$state/systemd/dotfiles-update.timer
            manager_service=$MOCK_MANAGER_CONFIG/systemd/user/dotfiles-update.service
            manager_timer=$MOCK_MANAGER_CONFIG/systemd/user/dotfiles-update.timer
            [ ! -e "$XDG_CONFIG_HOME/systemd/user/dotfiles-update.service" ]
            [ "$(readlink -f -- "$manager_service")" = "$(readlink -f -- "$definition")" ]
            [ "$(readlink -f -- "$manager_timer")" = "$(readlink -f -- "$timer")" ]
            grep -x 'Type=oneshot' "$definition"
            grep -x 'TimeoutStartSec=120' "$definition"
            grep -F 'ExecStart=/bin/sh "' "$definition"
            grep -F '\" '\'' %% $$ \\/maintain.sh" update' "$definition"
            grep -F 'Environment="XDG_CONFIG_HOME=' "$definition"
            grep -F 'Linux config &' "$definition"
            ! grep -F 'XDG_CONFIG_HOME=' "$timer"
            grep -F 'Environment="XDG_STATE_HOME=' "$definition"
            grep -F 'state & \" %% $ \\' "$definition"
            ! grep -F 'ignored state home' "$definition"
            grep -x 'OnCalendar=\*-\*-\* \*:0/15:00' "$timer"
            grep -x 'Persistent=true' "$timer"
            if command -v systemd-analyze >/dev/null 2>&1; then
                systemd-analyze verify "$definition" "$timer"
            fi
            ;;
    esac
    grep -F '/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin' "$definition"
    if [ "$MOCK_OS" = Darwin ]; then ! grep -F 'ignored state home' "$definition"; fi
    cp "$definition" "$root/before"
    cp "$MOCK_LOG" "$root/log-before-identical"
    [ "$(run enable)" = enabled ]
    cmp "$definition" "$root/before"
    if [ "$MOCK_OS" = Linux ]; then
        [ "$(readlink -f -- "$MOCK_MANAGER_CONFIG/systemd/user/dotfiles-update.service")" = "$(readlink -f -- "$definition")" ]
    fi
    # Refresh changed descriptors with the new checkout without accumulating jobs.
    checkout="$checkout changed"
    [ "$(run enable)" = enabled ]
    ! cmp -s "$definition" "$root/before"
    grep -F ' changed/maintain.sh' "$definition"
    if [ "$MOCK_OS" = Darwin ]; then
        cp "$MOCK_LOADED" "$root/loaded-before-retry"
        checkout="$checkout requested"
        XDG_CONFIG_HOME="$root/Darwin requested config"
        XDG_STATE_HOME="$root/Darwin requested state"
        state=$XDG_STATE_HOME/dotfiles
        MOCK_BOOTOUT_FAIL_ONCE=1; export MOCK_BOOTOUT_FAIL_ONCE
        expect_failure enable
        cmp "$MOCK_LOADED" "$root/loaded-before-retry"
        ! cmp -s "$definition" "$MOCK_LOADED"
        grep -F ' changed requested/maintain.sh</string>' "$definition"
        grep -F "<string>$XDG_CONFIG_HOME</string>" "$definition"
        grep -F "<string>$XDG_STATE_HOME</string>" "$definition"
        [ "$(run enable)" = enabled ]
        cmp "$definition" "$MOCK_LOADED"
        grep -F ' changed requested/maintain.sh</string>' "$MOCK_LOADED"
        grep -F "<string>$XDG_CONFIG_HOME</string>" "$MOCK_LOADED"
        grep -F "<string>$XDG_STATE_HOME</string>" "$MOCK_LOADED"
    fi
    if [ "$MOCK_OS" = Linux ]; then
        # Caller config remains an environment value; manager links stay state-owned.
        original_manager_service=$(readlink -f -- "$manager_service")
        XDG_CONFIG_HOME="$root/caller config changed & \""
        export XDG_CONFIG_HOME
        cp "$MOCK_LOG" "$root/log-before-caller-change"
        [ "$(run status)" = enabled ]
        cmp "$MOCK_LOG" "$root/log-before-caller-change"
        [ "$(run enable)" = enabled ]
        [ "$(readlink -f -- "$manager_service")" = "$original_manager_service" ]
        grep -F 'caller config changed &' "$definition"
        # A different state root conflicts with existing manager links and must not replace them.
        old_state=$state
        state="$root/new state root/dotfiles"
        MOCK_EXPECTED_SOURCE=$state/systemd; export MOCK_EXPECTED_SOURCE
        expect_failure enable
        [ ! -e "$state" ]
        [ "$(readlink -f -- "$manager_service")" = "$original_manager_service" ]
        state=$old_state
        MOCK_EXPECTED_SOURCE=$state/systemd; export MOCK_EXPECTED_SOURCE
        XDG_CONFIG_HOME="$root/Linux config & \" % \$ \\"; export XDG_CONFIG_HOME
        # Loaded identity can be stale when someone replaces an installed alias.
        mkdir -p "$root/foreign-current"
        for replaced_unit in dotfiles-update.service dotfiles-update.timer; do
            alias=$MOCK_MANAGER_CONFIG/systemd/user/$replaced_unit
            source=$MOCK_EXPECTED_SOURCE/$replaced_unit
            [ "$(systemctl --user show --property=FragmentPath --value "$replaced_unit")" = "$source" ]
            mv "$alias" "$root/owned-alias"
            printf 'foreign definition\n' > "$root/foreign-current/$replaced_unit"
            ln -s "$root/foreign-current/$replaced_unit" "$alias"
            # No reload: the manager still reports the previously loaded source.
            [ "$(systemctl --user show --property=FragmentPath --value "$replaced_unit")" = "$source" ]
            cp "$definition" "$root/owned-service-before"
            cp "$timer" "$root/owned-timer-before"
            cp "$MOCK_LOG" "$root/log-before-stale-fragment"
            expect_failure disable
            [ "$(readlink "$alias")" = "$root/foreign-current/$replaced_unit" ]
            [ "$(cat "$root/foreign-current/$replaced_unit")" = 'foreign definition' ]
            [ -f "$MOCK_ENABLED" ] && [ -f "$MOCK_LOADED" ]
            cmp "$definition" "$root/owned-service-before"
            cmp "$timer" "$root/owned-timer-before"
            assert_reloaded_only "$root/log-before-stale-fragment"
            rm "$alias"
            mv "$root/owned-alias" "$alias"
            systemctl --user daemon-reload >/dev/null
        done
    fi
    # Missing owned definitions must not hide a running native job or timer.
    cp "$MOCK_LOG" "$root/log-before-missing-definitions"
    case "$MOCK_OS" in
        Darwin)
            cp "$definition" "$root/missing-definition"
            rm "$definition"
            expect_failure disable
            [ -f "$MOCK_LOADED" ]
            cmp "$MOCK_LOG" "$root/log-before-missing-definitions"
            mv "$root/missing-definition" "$definition"
            ;;
        Linux)
            cp "$definition" "$root/missing-service"
            cp "$timer" "$root/missing-timer"
            rm "$definition" "$timer" "$MOCK_ENABLED"
            [ "$(run status)" = 'active (not enabled)' ]
            expect_failure disable
            [ -f "$MOCK_LOADED" ]
            assert_reloaded_only "$root/log-before-missing-definitions"
            mv "$root/missing-service" "$definition"
            mv "$root/missing-timer" "$timer"
            : > "$MOCK_ENABLED"
            rm "$MOCK_LOADED"
            [ "$(run status)" = 'enabled (inactive)' ]
            : > "$MOCK_LOADED"
            # Empty manager fragments cannot justify destructive action while the timer is live.
            cp "$MOCK_LOG" "$root/log-before-empty-fragments"
            rm "$manager_service" "$manager_timer"
            expect_failure disable
            [ -f "$MOCK_ENABLED" ] && [ -f "$MOCK_LOADED" ]
            [ -f "$definition" ] && [ -f "$timer" ]
            assert_reloaded_only "$root/log-before-empty-fragments"
            ln -s "$definition" "$manager_service"
            ln -s "$timer" "$manager_timer"
            ;;
    esac
    # Neither status nor preview can touch descriptor contents or scheduler state.
    cp "$definition" "$root/before"
    cp "$MOCK_LOG" "$root/log-before"
    run status > "$root/status"
    run enable --dry-run > "$root/preview"
    run disable --dry-run > "$root/preview"
    cmp "$definition" "$root/before"
    cmp "$MOCK_LOG" "$root/log-before"
    # Preserve neighboring user work; repeated disable is a no-op.
    printf 'user work\n' > "$(dirname "$definition")/unrelated.conf"
    : > "$MOCK_SERVICE_ACTIVE"
    [ "$(run disable)" = disabled ]
    [ "$(run status)" = disabled ]
    if [ "$MOCK_OS" = Linux ]; then
        [ -f "$definition" ] && [ -f "$timer" ]
        [ ! -e "$manager_service" ] && [ ! -e "$manager_timer" ]
        grep -F -x 'DisableUnitFiles 2 dotfiles-update.service dotfiles-update.timer false' "$MOCK_LOG"
        [ -f "$MOCK_SERVICE_ACTIVE" ]
        # Keep source files while an in-flight service still has a manager fragment.
        rm -f "$MOCK_SERVICE_ACTIVE"
        [ "$(run disable)" = disabled ]
        [ ! -e "$definition" ] && [ ! -e "$timer" ]
    else
        [ ! -e "$definition" ]
    fi
    cp "$MOCK_LOG" "$root/log-before"
    [ "$(run disable)" = disabled ]
    cmp "$MOCK_LOG" "$root/log-before"
    [ "$(cat "$(dirname "$definition")/unrelated.conf")" = 'user work' ]
    rm -f "$MOCK_SERVICE_ACTIVE"
    # An unmanaged file or symlink at our name must not be replaced or removed.
    printf 'user work\n' > "$definition"
    expect_failure enable
    expect_failure disable
    [ "$(cat "$definition")" = 'user work' ]
    rm "$definition"
    ln -s "$(dirname "$definition")/unrelated.conf" "$definition"
    expect_failure enable
    expect_failure disable
    [ -L "$definition" ]
    rm "$definition"
    # Unreachable native managers and failed registration are explicit errors.
    MOCK_UNAVAILABLE=1; export MOCK_UNAVAILABLE
    expect_failure enable
    [ ! -e "$definition" ]
    MOCK_UNAVAILABLE=0; export MOCK_UNAVAILABLE
    MOCK_FAIL=1; export MOCK_FAIL
    expect_failure enable
    [ "$(run status)" = disabled ]
    MOCK_FAIL=0; export MOCK_FAIL
    if [ "$MOCK_OS" = Linux ]; then
        # Only the discovered owned name is disabled when registration is partial.
        rm "$MOCK_MANAGER_CONFIG/systemd/user/dotfiles-update.timer"
        rm -f "$MOCK_ENABLED" "$MOCK_LOADED"
        [ "$(run disable)" = disabled ]
        grep -F -x 'DisableUnitFiles 1 dotfiles-update.service false' "$MOCK_LOG"
        [ ! -e "$MOCK_MANAGER_CONFIG/systemd/user/dotfiles-update.service" ]
        [ ! -e "$definition" ] && [ ! -e "$timer" ]
    else
        run disable > "$root/disabled"
        grep -F 'bootout gui/501/com.snowykr.dotfiles.update' "$MOCK_LOG"
    fi
    # command-not-found must never fall through to a real scheduler.
    if PATH="$root/missing" /bin/sh "$repo/scripts/scheduler.sh" enable "$checkout" "$state" > "$root/error"; then exit 1; fi
    if [ "$MOCK_OS" = Linux ]; then
        mkdir -p "$root/no-busctl"
        cp "$root/stubs/uname" "$root/stubs/systemctl" "$root/no-busctl/"
        if PATH="$root/no-busctl" /bin/sh "$repo/scripts/scheduler.sh" enable "$checkout" "$state" > "$root/error"; then exit 1; fi
        [ ! -e "$definition" ]
    fi
done
# A custom user-manager config root is independent of the caller's default/custom config.
MOCK_OS=Linux
HOME="$root/manager custom home"
unset XDG_CONFIG_HOME
state="$root/manager custom state/dotfiles"
MOCK_MANAGER_CONFIG="$root/manager custom config & punct"
MOCK_EXPECTED_SOURCE=$state/systemd
MOCK_LOG="$root/manager-custom.mutations"
MOCK_LOADED="$root/manager-custom.loaded"
MOCK_ENABLED="$root/manager-custom.enabled"
MOCK_SERVICE_ACTIVE="$root/manager-custom.service-active"
MOCK_UNAVAILABLE=0
MOCK_FAIL=0
